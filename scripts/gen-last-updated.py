"""Generate src/data/last-updated.ts from real git history.

The sitemap used to stamp every URL with `new Date()`, so all 62 pages claimed to
have been updated at build time on every deploy. Search engines learn to ignore a
lastmod that never varies, and a genuine content change stops being a freshness
signal. This writes the date of the newest commit touching each page's own source
plus the shared component and data file it renders from.

    python3 scripts/gen-last-updated.py
"""

from __future__ import annotations

import os
import subprocess
import sys

APP = "src/app"
OUT = os.path.join("src", "data", "last-updated.ts")
UNIT_COMPONENT = "src/components/MorseUnitPage.tsx"
UNIT_DATA = "src/data/morse-units.ts"
WORD_DATA = "src/data/morse-words.ts"
DATE = "%Y-%m-%d"


def git_date(paths: list[str]) -> str | None:
    """Newest commit date across every path that exists."""
    existing = [p for p in paths if os.path.exists(p)]
    if not existing:
        return None
    dates = []
    for p in existing:
        r = subprocess.run(
            ["git", "log", "-1", f"--format=%cd", f"--date=format:{DATE}", "--", p],
            capture_output=True,
            text=True,
        )
        if r.stdout.strip():
            dates.append(r.stdout.strip())
    return max(dates) if dates else None


def routes() -> list[str]:
    out = []
    if os.path.exists(os.path.join(APP, "page.tsx")):
        out.append("")
    for name in sorted(os.listdir(APP)):
        if os.path.isdir(os.path.join(APP, name)) and os.path.exists(
            os.path.join(APP, name, "page.tsx")
        ):
            out.append(name)
    return out


def main() -> int:
    start = subprocess.run(
        ["git", "log", "--reverse", "--format=%cd", f"--date=format:{DATE}"],
        capture_output=True,
        text=True,
    ).stdout.strip().splitlines()
    if not start:
        print("git history is empty; nothing to derive", file=sys.stderr)
        return 1

    table: dict[str, str] = {}
    missing = []
    for slug in routes():
        own = os.path.join(APP, slug, "page.tsx") if slug else os.path.join(APP, "page.tsx")
        paths = [own]
        if slug.endswith("-in-morse-code"):
            paths += [UNIT_COMPONENT, UNIT_DATA, WORD_DATA]
        elif slug in ("", "alphabet", "numbers", "chart"):
            paths += [UNIT_DATA]
        date = git_date(paths)
        if date is None:
            missing.append(slug)
            date = start[0]
        table[slug or "/"] = date

    lines = [
        "// Generated by scripts/gen-last-updated.py - do not edit.",
        "// Newest real commit touching each page's own source plus the shared",
        "// component and data files it renders from.",
        "export const SITE_START = '%s';" % start[0],
        "",
        "export const LAST_UPDATED: Record<string, string> = {",
    ]
    for slug, date in sorted(table.items()):
        lines.append("  '%s': '%s'," % (slug, date))
    lines += ["};", ""]

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    distinct = sorted({d for d in table.values()})
    print(f"wrote {OUT}: {len(table)} entries, {len(distinct)} distinct dates {distinct}")
    if missing:
        print(f"{len(missing)} pages had no git history and fell back to SITE_START: {missing}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
